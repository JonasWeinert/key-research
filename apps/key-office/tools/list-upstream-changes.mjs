/**
 * Writes UPSTREAM-CHANGES.txt: which files under apps/key-office Key changed, added or
 * removed relative to the GenOffice commit it was cloned from. Apache-2.0 section 4(b)
 * asks modified files to carry a notice that they were changed; this list (referenced
 * from NOTICE and UPSTREAM.md) is that notice for the whole tree.
 *
 *   node tools/list-upstream-changes.mjs   (needs `gh` signed in, or --tree <file>
 *   with "<blob sha> <path>" lines from the upstream tree)
 */
import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const UPSTREAM = 'genspark-ai/genoffice'
const COMMIT = 'de139a061537bea40f0cc81ef8f09a95f77ac52a'

const treeArg = process.argv.indexOf('--tree')
const treeText =
  treeArg > 0
    ? readFileSync(process.argv[treeArg + 1], 'utf8')
    : execFileSync('gh', ['api', `repos/${UPSTREAM}/git/trees/${COMMIT}?recursive=1`, '--jq', '.tree[]|select(.type=="blob")|.sha+" "+.path'], {
        encoding: 'utf8',
        maxBuffer: 64 * 1024 * 1024,
      })
const upstream = new Map(
  treeText
    .trim()
    .split('\n')
    .map((l) => [l.slice(l.indexOf(' ') + 1), l.slice(0, l.indexOf(' '))]),
)
// blob ids of the committed files (working-tree edits are not counted)
const ours = new Map(
  execFileSync('git', ['ls-files', '-s', '.'], { cwd: ROOT, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 })
    .trim()
    .split('\n')
    .map((l) => {
      const [meta, path] = l.split('\t')
      return [path, meta.split(' ')[1]]
    }),
)

const modified = [...ours].filter(([p, sha]) => upstream.has(p) && upstream.get(p) !== sha).map(([p]) => p)
const added = [...ours.keys()].filter((p) => !upstream.has(p))
const removed = [...upstream.keys()].filter((p) => !ours.has(p))
const unchanged = ours.size - modified.length - added.length

const list = (title, paths) => `\n${title} (${paths.length})\n\n${paths.sort().map((p) => `  ${p}`).join('\n')}\n`
const out = `Changes Key made to GenOffice
=============================

Upstream: https://github.com/${UPSTREAM} at ${COMMIT} (Apache-2.0,
Copyright 2026 Mainfunc, Inc.). Paths are relative to apps/key-office.

Files listed as modified were changed by Key (product branding, shell integration,
theming, fixes and features); they remain under the Apache License 2.0. Files added by
Key are Key's own work under the MIT licence, except where a file header says otherwise
(apps/key/src/renderer/TabBar.tsx and tabbar.css derive from GenOffice's shell and stay
Apache-2.0; packages/design-system and apps/key/src/renderer/motion adapt MIT beUI code).
See LICENSES.md at the repository root. ${unchanged} files are unchanged from upstream.

Generated by tools/list-upstream-changes.mjs; regenerate after changing upstream files.
${list('Modified by Key', modified)}${list('Added by Key', added)}${list('Removed (not included in Key)', removed)}`
writeFileSync(join(ROOT, 'UPSTREAM-CHANGES.txt'), out)
console.log(`UPSTREAM-CHANGES.txt: ${modified.length} modified, ${added.length} added, ${removed.length} removed, ${unchanged} unchanged`)
